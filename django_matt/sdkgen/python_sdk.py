    def _generate_sync_method(self, lines: list[str], ep: Endpoint, prefix: str) -> None:
        method_name = to_snake_case(sanitize_identifier(ep.operation_id))
        params, path_expr, body_arg, query_arg = self._method_parts(ep)

        sig = ", ".join(["self"] + params)
        return_type = self._return_type(ep)

        if ep.summary:
            lines.append(f'{prefix}def {method_name}({sig}) -> {return_type}:')
            lines.append(f'{prefix}    """{ep.summary}"""')
        else:
            lines.append(f"{prefix}def {method_name}({sig}) -> {return_type}:")

        lines.append(f'{prefix}    return self._request("{ep.method}", {path_expr}{body_arg}{query_arg})')
        lines.append("")

    def _generate_async_method(self, lines: list[str], ep: Endpoint, prefix: str) -> None:
        method_name = to_snake_case(sanitize_identifier(ep.operation_id))
        params, path_expr, body_arg, query_arg = self._method_parts(ep)

        sig = ", ".join(["self"] + params)
        return_type = self._return_type(ep)

        if ep.summary:
            lines.append(f'{prefix}async def {method_name}({sig}) -> {return_type}:')
            lines.append(f'{prefix}    """{ep.summary}"""')
        else:
            lines.append(f"{prefix}async def {method_name}({sig}) -> {return_type}:")

        lines.append(f'{prefix}    return await self._request("{ep.method}", {path_expr}{body_arg}{query_arg})')
        lines.append("")

    def _method_parts(self, ep: Endpoint) -> tuple[list[str], str, str, str]:
        """Build method parameters, path expression, body arg, query arg."""
        params: list[str] = []

        # Path params
        for p in ep.parameters:
            if p.location == "path":
                py_type = openapi_type_to_python(p.schema) if p.schema else "str"
                params.append(f"{to_snake_case(p.name)}: {py_type}")

        # Body
        body_arg = ""
        if ep.request_body_ref:
            body_type = to_pascal_case(sanitize_identifier(ep.request_body_ref))
            params.append(f"data: {body_type}")
            body_arg = ", json=data.model_dump(mode='json')"
        elif ep.request_body_schema and ep.request_body_schema.get("type") == "object":
            params.append("data: dict[str, Any]")
            body_arg = ", json=data"

        # Query params
        query_params = [p for p in ep.parameters if p.location == "query"]
        query_arg = ""
        if query_params:
            for qp in query_params:
                py_type = openapi_type_to_python(qp.schema) if qp.schema else "str"
                default = " = None" if not qp.required else ""
                if not qp.required:
                    py_type = f"{py_type} | None"
                params.append(f"{to_snake_case(qp.name)}: {py_type}{default}")
            param_names = [to_snake_case(qp.name) for qp in query_params]
            dict_items = ", ".join(f'"{qp.name}": {to_snake_case(qp.name)}' for qp in query_params)
            query_arg = f", params={{{dict_items}}}"

        # Path expression
        path = ep.path
        path_params = [p for p in ep.parameters if p.location == "path"]
        if path_params:
            for p in path_params:
                path = path.replace(f"{{{p.name}}}", f"{{{to_snake_case(p.name)}}}")
            path_expr = f'f"{path}"'
        else:
            path_expr = f'"{path}"'

        return params, path_expr, body_arg, query_arg

    def _return_type(self, ep: Endpoint) -> str:
        if ep.response_ref:
            return to_pascal_case(sanitize_identifier(ep.response_ref))
        return "Any"

    def _collect_model_refs(self, api: ParsedAPI) -> set[str]:
        refs: set[str] = set()
        for ep in api.endpoints:
            if ep.request_body_ref:
                refs.add(to_pascal_case(sanitize_identifier(ep.request_body_ref)))
            if ep.response_ref:
                refs.add(to_pascal_case(sanitize_identifier(ep.response_ref)))
        return refs

