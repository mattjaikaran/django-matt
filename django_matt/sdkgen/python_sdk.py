"""Python SDK generator — produces a complete PyPI-publishable package."""

from __future__ import annotations

from typing import Any

from django_matt.sdkgen.base import SDKConfig, SDKGenerator, SDKOutput
from django_matt.sdkgen.schema_parser import Endpoint, ParsedAPI, SchemaParser
from django_matt.sdkgen.template_engine import (
    openapi_type_to_python,
    sanitize_identifier,
    to_pascal_case,
    to_snake_case,
)


class PythonSDKGenerator(SDKGenerator):
    """Generate a complete Python SDK package from an OpenAPI schema."""

    target = "python"

    def generate(self, api_schema: dict[str, Any], config: SDKConfig) -> SDKOutput:
        parser = SchemaParser(api_schema)
        api = parser.parse()

        pkg = to_snake_case(config.package_name).replace("-", "_")
        files: dict[str, str] = {}

        if config.include_models:
            files[f"{pkg}/models.py"] = self._generate_models(api)

        files[f"{pkg}/errors.py"] = self._generate_errors()
        files[f"{pkg}/auth.py"] = self._generate_auth()

        if config.include_client:
            files[f"{pkg}/client.py"] = self._generate_client(api, config, pkg)

        files[f"{pkg}/__init__.py"] = self._generate_init(pkg, config)

        pyproject = self._generate_pyproject(config, api, pkg)
        files["pyproject.toml"] = pyproject
        files["README.md"] = self._generate_readme(api, config, pkg)

        return SDKOutput(files=files, package_config=pyproject, target=self.target)

    def _generate_models(self, api: ParsedAPI) -> str:
        lines: list[str] = [
            '"""Auto-generated by django_matt.sdkgen — do not edit manually."""',
            "",
            "from __future__ import annotations",
            "",
            "from datetime import date, datetime",
            "from enum import Enum",
            "from typing import Any",
            "",
            "from pydantic import BaseModel, Field",
            "",
            "",
        ]

        for name, model in api.models.items():
            py_name = to_pascal_case(sanitize_identifier(name))

            # Enum model
            if model.enum_values is not None:
                if all(isinstance(v, str) for v in model.enum_values):
                    lines.append(f"class {py_name}(str, Enum):")
                    for v in model.enum_values:
                        attr = sanitize_identifier(to_snake_case(str(v))).upper()
                        lines.append(f'    {attr} = "{v}"')
                else:
                    lines.append(f"class {py_name}(Enum):")
                    for v in model.enum_values:
                        attr = sanitize_identifier(str(v)).upper()
                        lines.append(f"    V_{attr} = {v!r}")
                lines.append("")
                lines.append("")
                continue

            # BaseModel
            bases = ["BaseModel"]
            if model.all_of:
                for sub in model.all_of:
                    if "$ref" in sub:
                        ref_name = sub["$ref"].rsplit("/", 1)[-1]
                        bases = [to_pascal_case(sanitize_identifier(ref_name))]

            if model.description:
                lines.append(f"class {py_name}({', '.join(bases)}):")
                lines.append(f'    """{model.description}"""')
            else:
                lines.append(f"class {py_name}({', '.join(bases)}):")

            props = dict(model.properties)
            if model.all_of:
                for sub in model.all_of:
                    if "$ref" not in sub:
                        props.update(sub.get("properties", {}))

            if not props:
                lines.append("    pass")
            else:
                for prop_name, prop_schema in props.items():
                    py_type = openapi_type_to_python(prop_schema)
                    field_name = to_snake_case(prop_name)
                    is_required = prop_name in model.required_fields
                    desc = prop_schema.get("description", "")

                    if is_required:
                        if desc:
                            lines.append(f'    {field_name}: {py_type} = Field(description="{desc}")')
                        else:
                            lines.append(f"    {field_name}: {py_type}")
                    elif desc:
                        lines.append(f'    {field_name}: {py_type} | None = Field(default=None, description="{desc}")')
                    else:
                        lines.append(f"    {field_name}: {py_type} | None = None")

            lines.append("")
            lines.append("")

        return "\n".join(lines)

