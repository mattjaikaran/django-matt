    def _collect_model_refs(self, api: ParsedAPI) -> set[str]:
        """Collect all model type names referenced by endpoints."""
        refs: set[str] = set()
        for ep in api.endpoints:
            if ep.request_body_ref:
                refs.add(to_pascal_case(sanitize_identifier(ep.request_body_ref)))
            if ep.response_ref:
                refs.add(to_pascal_case(sanitize_identifier(ep.response_ref)))
        return refs

    @staticmethod
    def _group_by_tag(endpoints: list[Endpoint]) -> dict[str, list[Endpoint]]:
        grouped: dict[str, list[Endpoint]] = {}
        for ep in endpoints:
            tag = ep.tags[0] if ep.tags else "default"
            grouped.setdefault(tag, []).append(ep)
        return grouped
