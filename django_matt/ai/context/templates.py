    lines = ["## Data Models", ""]

    for model in models[:max_models]:
        lines.append(f"### `{model['app_label']}.{model['name']}`")
        if model.get("docstring"):
            lines.append(f"_{model['docstring'].split(chr(10))[0]}_")
        lines.append("")

        lines.append("| Field | Type | Notes |")
        lines.append("|-------|------|-------|")

        for field in model.get("fields", [])[:15]:
            notes = []
