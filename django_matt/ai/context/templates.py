def format_auth_section(endpoints: list[dict[str, Any]]) -> str:
    """Format authentication section."""
    # Group endpoints by auth requirement
    auth_groups: dict[str, list[str]] = {}
    for ep in endpoints:
        auth = ep.get("auth_requirement", "none")
        if auth not in auth_groups:
            auth_groups[auth] = []
        auth_groups[auth].append(f"`{ep['method']} {ep['path']}`")

    if not auth_groups or (len(auth_groups) == 1 and "none" in auth_groups):
        return ""

    lines = ["## Authentication Requirements", ""]

    auth_labels = {
        "jwt_required": "JWT Required",
        "jwt_optional": "JWT Optional",
        "api_key": "API Key Required",
        "session": "Session Required",
        "permission_required": "Permission Required",
        "role_required": "Role Required",
        "none": "Public (No Auth)",
    }

    for auth_type, endpoints_list in auth_groups.items():
        label = auth_labels.get(auth_type, auth_type)
        lines.append(f"### {label}")
        for ep in endpoints_list[:10]:
            lines.append(f"- {ep}")
        if len(endpoints_list) > 10:
            lines.append(f"- ... and {len(endpoints_list) - 10} more")
        lines.append("")

    return "\n".join(lines)


